"""Generate `benchmark_samples.py`, which `main.py` imports (`SAMPLES`, `random_sample`).

`main.py` describes that module as auto-generated, but neither it nor a generator was in the repository, so the
worker could not start. This writes three synthetic 48 kHz 16-bit WAV clips, base64-encoded, as its docstring
specifies: a 4 s 440 Hz tone, an 8 s frequency-modulated harmonic stack, and 4 s of band-limited noise.
They only exercise decoding and timing; the classifier finds no song in them.
"""
import base64
import io
import wave
import numpy as np

SR = 48000


def wav_b64(x):
    buf = io.BytesIO()
    with wave.open(buf, 'wb') as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes((np.clip(x, -1, 1) * 32767).astype('<i2').tobytes())
    return base64.b64encode(buf.getvalue()).decode()


def main():
    rng = np.random.default_rng(0)
    t4, t8 = np.arange(4 * SR) / SR, np.arange(8 * SR) / SR
    tone = 0.3 * np.sin(2 * np.pi * 440 * t4)
    fm = sum(0.15 / k * np.sin(2 * np.pi * 300 * k * t8 + 3 * np.sin(2 * np.pi * 2 * t8)) for k in (1, 2, 3, 5))
    spec = np.fft.rfft(rng.normal(0, 1, 4 * SR)); f = np.fft.rfftfreq(4 * SR, 1 / SR); spec[(f < 200) | (f > 4000)] = 0
    noise = np.fft.irfft(spec); noise = 0.3 * noise / np.abs(noise).max()
    samples = {'short_tone': wav_b64(tone), 'multi_tone': wav_b64(fm), 'noise_burst': wav_b64(noise)}
    with open('benchmark_samples.py', 'w') as fh:
        fh.write('"""Auto-generated by make_benchmark_samples.py; do not edit."""\nimport random\n\nSAMPLES = {\n')
        for name, b64 in samples.items():
            fh.write(f'    {name!r}: {b64!r},\n')
        fh.write('}\n\n\ndef random_sample():\n    name = random.choice(list(SAMPLES))\n    return name, SAMPLES[name]\n')


if __name__ == '__main__':
    main()
